(function () {
	'use strict';

	var selector = '.ssys-gallery iframe[data-ssys-player]';
	var allowedOrigins = [ 'https://www.youtube.com', 'https://www.youtube-nocookie.com' ];
	var paletteVariables = [
		'--ast-global-color-0',
		'--ast-global-color-1',
		'--ast-global-color-2',
		'--ast-global-color-3',
		'--ast-global-color-4',
		'--ast-global-color-5',
		'--ast-global-color-6',
		'--ast-global-color-7',
		'--wp--preset--color--base',
		'--wp--preset--color--contrast',
		'--e-global-color-primary',
		'--e-global-color-secondary',
		'--e-global-color-text',
		'--e-global-color-accent'
	];

	function parseColor(value) {
		var match = String(value || '').match(/rgba?\(\s*(\d+(?:\.\d+)?)\D+(\d+(?:\.\d+)?)\D+(\d+(?:\.\d+)?)(?:\D+(\d*(?:\.\d+)?))?\s*\)/i);
		if (!match) {
			var sample = document.createElement('span');
			sample.style.color = value;
			sample.style.display = 'none';
			document.body.appendChild(sample);
			var resolved = window.getComputedStyle(sample).color;
			sample.remove();
			if (resolved && resolved !== value) {
				return parseColor(resolved);
			}
			return null;
		}
		return {
			r: Number(match[1]),
			g: Number(match[2]),
			b: Number(match[3]),
			a: typeof match[4] === 'undefined' || '' === match[4] ? 1 : Number(match[4])
		};
	}

	function luminance(color) {
		return [ color.r, color.g, color.b ].map(function (channel) {
			channel /= 255;
			return channel <= 0.03928 ? channel / 12.92 : Math.pow((channel + 0.055) / 1.055, 2.4);
		}).reduce(function (sum, channel, index) {
			return sum + channel * [ 0.2126, 0.7152, 0.0722 ][index];
		}, 0);
	}

	function contrast(first, second) {
		var light = Math.max(luminance(first), luminance(second));
		var dark = Math.min(luminance(first), luminance(second));
		return (light + 0.05) / (dark + 0.05);
	}

	function effectiveBackgrounds(element) {
		for (var node = element; node; node = node.parentElement) {
			var styles = window.getComputedStyle(node);
			var imageColors = String(styles.backgroundImage || '').match(/rgba?\([^)]*\)/gi) || [];
			imageColors = imageColors.map(parseColor).filter(function (color) {
				return color && color.a >= 0.85;
			});
			if (imageColors.length) {
				return imageColors;
			}

			var color = parseColor(styles.backgroundColor);
			if (color && color.a >= 0.85) {
				return [ color ];
			}
		}
		return [ { r: 255, g: 255, b: 255, a: 1 } ];
	}

	function minimumContrast(foreground, backgrounds) {
		return Math.min.apply(null, backgrounds.map(function (background) {
			return contrast(foreground, background);
		}));
	}

	function applyThemeColor(element) {
		if (!element || element.dataset.ssysThemeColor === 'true') {
			return;
		}

		var backgrounds = effectiveBackgrounds(element);
		var rootStyles = window.getComputedStyle(document.documentElement);
		var current = window.getComputedStyle(element).color;
		var candidates = [ current ];
		paletteVariables.forEach(function (variable) {
			var value = rootStyles.getPropertyValue(variable).trim();
			if (value) {
				candidates.push(value);
			}
		});

		var best = { value: current, ratio: 0 };
		candidates.forEach(function (value) {
			var parsed = parseColor(value);
			if (parsed && parsed.a >= 0.85) {
				var ratio = minimumContrast(parsed, backgrounds);
				if (ratio > best.ratio) {
					best = { value: value, ratio: ratio };
				}
			}
		});

		if (best.ratio < 4.5) {
			var white = { r: 255, g: 255, b: 255, a: 1 };
			var black = { r: 0, g: 0, b: 0, a: 1 };
			best = minimumContrast(white, backgrounds) >= minimumContrast(black, backgrounds) ? { value: '#fff' } : { value: '#000' };
		}

		element.style.setProperty('--ssys-title-color', best.value);
		element.style.setProperty('--ssys-message-color', best.value);
		element.dataset.ssysThemeColor = 'true';
	}

	function send(frame, payload) {
		if (!frame || !frame.contentWindow) {
			return;
		}

		var targetOrigin = 'https://www.youtube-nocookie.com';
		try {
			targetOrigin = new URL(frame.src, window.location.href).origin;
		} catch (error) {
			// The iframe URL is generated by the plugin; retain the privacy-domain fallback.
		}

		frame.contentWindow.postMessage(JSON.stringify(payload), targetOrigin);
	}

	function pauseOtherPlayers(activeFrame) {
		document.querySelectorAll(selector).forEach(function (frame) {
			if (frame !== activeFrame) {
				send(frame, { event: 'command', func: 'pauseVideo', args: [] });
			}
		});
	}

	function subscribe(frame) {
		if (frame.dataset.ssysListening === 'true') {
			return;
		}
		frame.dataset.ssysListening = 'true';

		var register = function () {
			send(frame, { event: 'listening', id: frame.id, channel: 'ssys' });
			send(frame, { event: 'command', func: 'addEventListener', args: [ 'onStateChange' ] });
		};

		frame.addEventListener('load', function () {
			register();
			window.setTimeout(register, 500);
			window.setTimeout(register, 1500);
		});

		register();
	}

	function subscribeAll(root) {
		if (root.matches && root.matches('.ssys-gallery, .ssys-message')) {
			applyThemeColor(root);
		}
		if (root.querySelectorAll) {
			root.querySelectorAll('.ssys-gallery, .ssys-message').forEach(applyThemeColor);
		}
		if (root.matches && root.matches(selector)) {
			subscribe(root);
		}
		if (root.querySelectorAll) {
			root.querySelectorAll(selector).forEach(subscribe);
		}
	}

	window.addEventListener('message', function (event) {
		if (allowedOrigins.indexOf(event.origin) === -1) {
			return;
		}

		var data = event.data;
		if (typeof data === 'string') {
			try {
				data = JSON.parse(data);
			} catch (error) {
				return;
			}
		}
		if (!data || data.event !== 'onStateChange' || Number(data.info) !== 1) {
			return;
		}

		var activeFrame = Array.prototype.find.call(
			document.querySelectorAll(selector),
			function (frame) {
				return frame.contentWindow === event.source;
			}
		);
		if (activeFrame) {
			pauseOtherPlayers(activeFrame);
		}
	});

	function init() {
		subscribeAll(document);
		new MutationObserver(function (mutations) {
			mutations.forEach(function (mutation) {
				mutation.addedNodes.forEach(function (node) {
					if (node.nodeType === 1) {
						subscribeAll(node);
					}
				});
			});
		}).observe(document.body, { childList: true, subtree: true });
	}

	if (document.readyState === 'loading') {
		document.addEventListener('DOMContentLoaded', init);
	} else {
		init();
	}
}());
